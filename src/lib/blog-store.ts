function ensureDirExists() {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
}

// ----------------- CATEGORIES -----------------

export function getCategories(): BlogCategory[] {
  try {
    ensureDirExists();
    if (!fs.existsSync(CATEGORIES_FILE)) {
      fs.writeFileSync(CATEGORIES_FILE, JSON.stringify(DEFAULT_CATEGORIES, null, 2), "utf8");
      return DEFAULT_CATEGORIES;
    }
    const raw = fs.readFileSync(CATEGORIES_FILE, "utf8");
    const categories: BlogCategory[] = JSON.parse(raw);
    const blogs = getBlogs();

    return categories.map((cat) => ({
      ...cat,
      postCount: blogs.filter((b) => b.categoryId === cat.id).length,
    }));
  } catch (err) {
    console.error("[blog-store] Error reading categories:", err);
    return DEFAULT_CATEGORIES;
  }
}

export function saveCategories(categories: BlogCategory[]): boolean {
  try {
    ensureDirExists();
    fs.writeFileSync(CATEGORIES_FILE, JSON.stringify(categories, null, 2), "utf8");
    return true;
  } catch (err) {
    console.error("[blog-store] Error saving categories:", err);
    return false;
  }
}

export function createCategory(input: {
  name: string;
  slug?: string;
  color?: string;
  description?: string;
}): { success: boolean; category?: BlogCategory; error?: string } {
  const name = input.name.trim();
  if (!name) return { success: false, error: "Category name is required" };

  const slug = (input.slug || name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")).trim();
  const categories = getCategories();

  if (categories.some((c) => c.slug === slug)) {
    return { success: false, error: `Category with slug '${slug}' already exists` };
  }

  const newCat: BlogCategory = {
    id: "cat-" + slug + "-" + Date.now().toString(36),
    name,
    slug,
    color: input.color || "#f7fe72",
    description: input.description?.trim() || "",
    createdAt: new Date().toISOString(),
  };

  categories.push(newCat);
  saveCategories(categories);
  return { success: true, category: newCat };
}

export function updateCategory(
  id: string,
  updates: Partial<Omit<BlogCategory, "id" | "createdAt">>
): { success: boolean; category?: BlogCategory; error?: string } {
  const categories = getCategories();
  const idx = categories.findIndex((c) => c.id === id);
  if (idx === -1) return { success: false, error: "Category not found" };

  const updated: BlogCategory = {
    ...categories[idx],
    ...updates,
  };

  categories[idx] = updated;
  saveCategories(categories);
  return { success: true, category: updated };
}

export function deleteCategory(id: string): { success: boolean; error?: string } {
  const categories = getCategories();
  const filtered = categories.filter((c) => c.id !== id);
  if (filtered.length === categories.length) return { success: false, error: "Category not found" };

  saveCategories(filtered);
  return { success: true };
}

// ----------------- BLOGS -----------------

export function getBlogs(): BlogPost[] {
  try {
    ensureDirExists();
    if (!fs.existsSync(BLOGS_FILE)) {
      fs.writeFileSync(BLOGS_FILE, JSON.stringify(DEFAULT_BLOGS, null, 2), "utf8");
      return DEFAULT_BLOGS;
    }
    const raw = fs.readFileSync(BLOGS_FILE, "utf8");
    const blogs: BlogPost[] = JSON.parse(raw);
    return Array.isArray(blogs) ? blogs : DEFAULT_BLOGS;
  } catch (err) {
    console.error("[blog-store] Error reading blogs:", err);
    return DEFAULT_BLOGS;
  }
}

export function saveBlogs(blogs: BlogPost[]): boolean {
  try {
    ensureDirExists();
    fs.writeFileSync(BLOGS_FILE, JSON.stringify(blogs, null, 2), "utf8");
    return true;
  } catch (err) {
    console.error("[blog-store] Error saving blogs:", err);
    return false;
  }
}

export function getBlogById(id: string): BlogPost | null {
  const blogs = getBlogs();
  return blogs.find((b) => b.id === id) || null;
}

export function getBlogBySlug(slug: string): BlogPost | null {
  const blogs = getBlogs();
  return blogs.find((b) => b.slug === slug) || null;
}

export function createBlog(input: Partial<BlogPost>): { success: boolean; blog?: BlogPost; error?: string } {
  if (!input.title?.trim()) {
    return { success: false, error: "Article title is required" };
  }

  const title = input.title.trim();
  const slug = (
    input.slug ||
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
  ).trim();

  const blogs = getBlogs();
  if (blogs.some((b) => b.slug === slug)) {
    return { success: false, error: `Article with slug '${slug}' already exists` };
  }

  const categories = getCategories();
  const cat = categories.find((c) => c.id === input.categoryId);

  const now = new Date().toISOString();
  const newPost: BlogPost = {
    id: "post-" + Date.now().toString(36) + "-" + Math.random().toString(36).substring(2, 6),
    title,
    slug,
    excerpt: input.excerpt?.trim() || "",
    content: input.content || "<p>Start writing your athletic protocol here...</p>",
    categoryId: input.categoryId || categories[0]?.id || "cat-athletic-fuel",
    categoryName: cat?.name || "Precision Athletic Fuel",
    coverImage: input.coverImage || "/assets/aistudio/image_b79abc29.png",
    readTime: input.readTime || "5 min read",
    tags: Array.isArray(input.tags) ? input.tags : ["Uchitatvam"],
    status: input.status || "draft",
    author: input.author || {
      name: "Uchitatvam Editorial",
      role: "Performance Research Team",
    },
    views: 0,
    createdAt: now,
    updatedAt: now,
    publishedAt: input.status === "published" ? now : undefined,
    seoTitle: input.seoTitle || title,
    seoDescription: input.seoDescription || input.excerpt,
  };

  blogs.unshift(newPost);
  saveBlogs(blogs);
  return { success: true, blog: newPost };
}

export function updateBlog(
  id: string,
  updates: Partial<BlogPost>
): { success: boolean; blog?: BlogPost; error?: string } {
  const blogs = getBlogs();
  const idx = blogs.findIndex((b) => b.id === id);
  if (idx === -1) return { success: false, error: "Article not found" };

  const existing = blogs[idx];
  const now = new Date().toISOString();

  let categoryName = existing.categoryName;
  if (updates.categoryId && updates.categoryId !== existing.categoryId) {
    const categories = getCategories();
    const cat = categories.find((c) => c.id === updates.categoryId);
    if (cat) categoryName = cat.name;
  }

  const updated: BlogPost = {
    ...existing,
    ...updates,
    categoryName,
    updatedAt: now,
    publishedAt:
      updates.status === "published" && !existing.publishedAt
        ? now
        : existing.publishedAt,
  };

  blogs[idx] = updated;
  saveBlogs(blogs);
  return { success: true, blog: updated };
}

export function deleteBlog(id: string): { success: boolean; error?: string } {
  const blogs = getBlogs();
  const filtered = blogs.filter((b) => b.id !== id);
  if (filtered.length === blogs.length) return { success: false, error: "Article not found" };

  saveBlogs(filtered);
  return { success: true };
}

export function bulkUpdateBlogs(
  ids: string[],
  updates: { status?: "published" | "draft" | "archived"; categoryId?: string }
): { success: boolean; count: number; updatedBlogs: BlogPost[] } {
  const blogs = getBlogs();
  const idSet = new Set(ids);
  const now = new Date().toISOString();

  let newCatName: string | undefined = undefined;
  if (updates.categoryId) {
    const categories = getCategories();
    const cat = categories.find((c) => c.id === updates.categoryId);
    if (cat) newCatName = cat.name;
  }

  let count = 0;
  const updatedBlogs: BlogPost[] = [];
  const modified = blogs.map((b) => {
    if (!idSet.has(b.id)) return b;
    count++;
    const postUpdated: BlogPost = {
      ...b,
      status: updates.status !== undefined ? updates.status : b.status,
      categoryId: updates.categoryId !== undefined ? updates.categoryId : b.categoryId,
      categoryName: updates.categoryId ? (newCatName || b.categoryName) : b.categoryName,
      updatedAt: now,
      publishedAt:
        updates.status === "published" && !b.publishedAt ? now : b.publishedAt,
    };
    updatedBlogs.push(postUpdated);
    return postUpdated;
  });

  saveBlogs(modified);
  return { success: true, count, updatedBlogs };
}

export function bulkToggleBlogStatus(
  ids: string[]
): { success: boolean; count: number; updatedBlogs: BlogPost[] } {
  const blogs = getBlogs();
  const idSet = new Set(ids);
  const now = new Date().toISOString();

  let count = 0;
  const updatedBlogs: BlogPost[] = [];
  const modified = blogs.map((b) => {
    if (!idSet.has(b.id)) return b;
    count++;
    const nextStatus = b.status === "published" ? "draft" : "published";
    const postUpdated: BlogPost = {
      ...b,
      status: nextStatus,
      updatedAt: now,
      publishedAt: nextStatus === "published" && !b.publishedAt ? now : b.publishedAt,
    };
    updatedBlogs.push(postUpdated);
    return postUpdated;
  });

  saveBlogs(modified);
  return { success: true, count, updatedBlogs };
}

export function bulkDeleteBlogs(ids: string[]): { success: boolean; count: number } {
  const blogs = getBlogs();
  const idSet = new Set(ids);
  const filtered = blogs.filter((b) => !idSet.has(b.id));
  const count = blogs.length - filtered.length;

  saveBlogs(filtered);
  return { success: true, count };
}
